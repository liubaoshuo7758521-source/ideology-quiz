#include <stdio.h>   // 引入标准输入输出库，用于scanf（输入）/printf（输出）
#include <stdlib.h>  // 引入标准库，用于malloc（申请内存）/free（释放内存）

// 定义单向链表的节点结构体：链表的最小单元
typedef struct Node {
    int val;                // 节点的数据域：存储整数类型的数值
    struct Node *next;      // 节点的指针域：指向链表中下一个节点的地址，用于串联节点
} Node;                     // 重命名结构体为Node，简化后续代码中结构体的使用

// 主函数：程序入口，一站式实现链表创建、插入、删除、输出、内存释放
int main() {
    // 定义变量：n=初始链表的节点个数；T=需要执行的操作次数
    int n, T;
    // 定义链表操作的核心指针：
    // head：头指针，始终指向链表第一个节点（链表的入口，所有操作从head开始）
    // tail：尾指针，始终指向链表最后一个节点（尾插法专用，避免每次找链表末尾）
    // temp：临时指针，用于暂存节点地址（避免链表断链/内存泄漏）
    Node *head = NULL, *tail = NULL, *temp;

    // ===================== 第一步：创建初始链表（尾插法） =====================
    // 读取初始链表的节点数量n（比如输入3，表示初始链表有3个节点）
    scanf("%d", &n);
    // 循环n次，逐个创建节点并拼接成链表
    for (int i = 0; i < n; i++) {
        // 1. 为新节点申请内存：
        // malloc返回void*类型，需强制转换为Node*（链表节点类型）；
        // sizeof(Node)计算一个节点占用的内存大小（int+指针，通常8/16字节，取决于系统）
        temp = (Node*)malloc(sizeof(Node));
        // 2. 读取用户输入的数值，存入新节点的data域（给节点赋值）
        scanf("%d", &temp->val);
        // 3. 初始化新节点的next指针为NULL：
        // 避免指针指向随机内存（野指针），链表最后一个节点的next必须是NULL
        temp->next = NULL;

        // 4. 尾插法：将新节点添加到链表末尾
        if (head == NULL) { // 链表为空（第一次创建节点）
            head = temp;    // 头指针指向第一个节点（确定链表的入口）
            tail = temp;    // 尾指针也指向第一个节点（此时链表只有一个节点，头尾重合）
        } else {            // 链表已有节点（非首次创建）
            tail->next = temp; // 原尾节点的next指针指向新节点（把新节点接在链表末尾）
            tail = temp;       // 尾指针更新为新节点（始终指向最后一个节点）
        }
    }

    // ===================== 第二步：处理T次插入/删除操作 =====================
    // 读取需要执行的操作次数T（比如输入2，表示要执行2次插入/删除）
    scanf("%d", &T);
    // 循环T次，逐个处理每一次操作
    for (int i = 0; i < T; i++) {
        // 定义操作相关变量：
        // op：操作类型（字符型，I=插入，D=删除）
        // index：操作位置（从0开始计数，0=表头，1=第一个节点后，以此类推）
        // val：插入操作的数值（删除操作不需要该变量）
        char op;
        int index, val;
        // 读取操作类型和位置：
        // %c前加空格：跳过输入中的换行/空格等空白字符，避免读错op（比如上一行的换行符被当成op）
        scanf(" %c %d", &op, &index);

        // ---------- 子逻辑1：处理插入操作（op='I'） ----------
        if (op == 'I') {
            // 读取插入操作的数值（插入需要指定新节点的数值，删除不需要）
            scanf("%d", &val);
            // 1. 创建新节点：申请内存+赋值+初始化next指针
            Node *newNode = (Node*)malloc(sizeof(Node)); // 为新节点申请内存
            newNode->val = val;   // 将插入的数值存入新节点的data域
            newNode->next = NULL; // 初始化next指针为NULL

            // 情况1：插入到表头（index=0）
            if (index == 0) {
                newNode->next = head; // 新节点的next指针指向原表头（接上头节点）
                head = newNode;       // 头指针更新为新节点（新节点成为链表新表头）
                continue;             // 跳过后续逻辑，直接处理下一次操作
            }

            // 情况2：插入到中间/尾部（index>0）
            // 定义cur指针：从表头开始遍历，找到插入位置的「前一个节点」
            // 比如插入到index=2的位置，需要先找到index=1的节点（前一个节点）
            Node *cur = head;
            // 循环index-1次，将cur指针移动到目标位置的前一个节点
            for (int j = 0; j < index - 1; j++) {
                cur = cur->next; // 指针后移，逐个节点遍历
            }
            // 插入核心逻辑：先连后断，避免链表断裂
            newNode->next = cur->next; // 新节点先接上cur的下一个节点（保留后续链表）
            cur->next = newNode;       // cur再接上新节点（完成插入）

            // 特殊处理：如果插入到链表尾部（新节点的next是NULL），更新尾指针
            if (newNode->next == NULL) {
                tail = newNode;
            }
        }
        // ---------- 子逻辑2：处理删除操作（op='D'） ----------
        else if (op == 'D') {
            // 情况1：删除表头节点（index=0）
            if (index == 0) {
                temp = head;       // 暂存原表头节点（释放内存前不能丢失指针）
                head = head->next; // 头指针后移，指向原表头的下一个节点（更新链表入口）
                free(temp);        // 释放被删除的表头节点（避免内存泄漏）
                continue;          // 跳过后续逻辑，直接处理下一次操作
            }

            // 情况2：删除中间/尾部节点（index>0）
            // 定义cur指针：从表头开始遍历，找到要删除节点的「前一个节点」
            Node *cur = head;
            // 循环index-1次，将cur指针移动到目标位置的前一个节点
            for (int j = 0; j < index - 1; j++) {
                cur = cur->next; // 指针后移，定位到前一个节点
            }
            temp = cur->next;       // 暂存要删除的节点（后续释放内存）
            cur->next = temp->next; // 跳过被删除节点，cur直接连接后面的节点（断链）

            // 特殊处理：如果删除的是链表尾部节点（cur的next变为NULL），更新尾指针
            if (cur->next == NULL) {
                tail = cur;
            }
            free(temp); // 释放被删除节点的内存（避免内存泄漏）
        }
    }

    // ===================== 第三步：遍历输出最终链表 =====================
    temp = head; // 重置temp指针到链表表头，准备遍历
    if (temp != NULL) { // 先处理第一个节点：避免空链表或末尾多空格
        printf("%d", temp->val); // 输出第一个节点的数值（无前置空格）
        temp = temp->next;       // 指针后移，指向第二个节点
    }
    // 遍历剩余节点：每个节点前加空格，避免末尾多空格
    while (temp != NULL) { // 只要指针不指向NULL（未到链表末尾），就继续遍历
        printf(" %d", temp->val); // 输出当前节点数值（前置空格）
        temp = temp->next;        // 指针后移，访问下一个节点
    }
    printf("\n"); // 输出换行符：符合多数OJ的格式要求（末尾需换行）

    // ===================== 第四步：释放链表内存（可选，避免内存泄漏） =====================
    temp = head; // 重置temp指针到链表表头，准备释放内存
    while (temp != NULL) { // 遍历链表，逐个释放节点
        Node *p = temp;    // 暂存当前节点的地址（释放前先保存）
        temp = temp->next; // 先将指针后移到下一个节点（避免释放后丢失链表）
        free(p);           // 释放当前节点的内存（归还给系统）
    }

    return 0; // 主函数正常结束，返回0表示程序执行成功
}