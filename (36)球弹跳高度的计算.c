/*
描述

 一球从某一高度h落下(单位米)，每次落地后反跳回原来高度的一半，再落下。编程计算气球在第10次落地时，共经过多少米? 第10次反弹多高？

输出包含两行，第1行：到球第10次落地时，一共经过的米数。第2行：第10次弹跳的高度。


输入描述

输入一个整数h，表示球的初始高度。


输出描述

第1行：到球第10次落地时，一共经过的米数。

   第2行：第10次弹跳的高度。

   注意：结果可能是实数，结果用double类型保存。

   提示：输出时不需要对精度特殊控制，用cout << ANSWER，或者printf("%g", ANSWER)即可。
   */
   #include <stdio.h>

int main() {
    int h;
    scanf("%d", &h);
    
    double total = h;  // 第1次落地经过的距离
    double height = h; // 当前反弹高度
    
    // 计算第2到第10次落地的距离（共9次反弹+下落）
    for (int i = 1; i <= 9; i++) {
        height /= 2;    // 本次反弹高度
        total += 2 * height; // 反弹+下落的距离
    }
    
    // 第10次反弹高度是第9次反弹高度的1/2
    height /= 2;
    
    // 输出结果
    printf("%g\n", total);
    printf("%g\n", height);
    
    return 0;
}